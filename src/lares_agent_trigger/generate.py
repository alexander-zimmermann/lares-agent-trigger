"""The generator: the declarations rendered into what the harness and its neighbours read.

Pure: the use-case file, the person declaration and the hand-written harness
settings in, one text per rendered file out. Which files, and what each
holds, is the README's "The generator", "The keys", "The gateway's routes" and
"The web chat's connections".
This module keeps the rules the rendering follows:

- a dormant use case, a tool server only dormant use cases name and a model
  source no profile runs on render nothing, and a dormant person nothing but
  their inactive account;
- every file is written whole and opens with the generated line, so a hand
  edit is overwritten by lares's pre-commit hook;
- every profile's config carries the hand-written settings as one mapping,
  parsed and dumped, their comments staying in settings.yaml; Hermes reads
  parts of a profile's file raw, so nothing may live outside it. The settings
  may carry no key the generator renders, neither at the top nor inside
  `discord` and `gateway`, where the rendered keys join the settings' own;
- a surface's toolset list follows how the harness resolves it: an explicit
  list without a server name hands the surface every server, so an empty one
  is the `no_mcp` sentinel; a list for Discord or cron starts with the
  platform's composite, the API server gets none;
- every value is sealed once: a variable's key is its name lower case and dashed, a
  person's own prefixed by the handle (their Discord id `<handle>-discord-user`),
  and the gateway reads each profile's key from the harness's SealedSecret, which
  shares its namespace;
- a route's keys are variables the gateway expands at start, a credential a
  file it watches, and a server outside the cluster is told nobody.
"""

