class _Dumper(yaml.SafeDumper):
    """Block style with indented sequences, the way the repository writes YAML."""

    @override
    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        super().increase_indent(flow, False)

    @override
    def ignore_aliases(self, data: Any) -> bool:
        # A list rendered twice is written twice, never as an anchor and its alias.
        return True


def _text(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    # A file inside a file stays readable: a multi-line string is a literal block.
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _text)


def _dump(data: Any) -> str:
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def render(declared: UseCaseFile, persons: PersonsFile, settings: str) -> Rendering:
    """Render the declarations; ``settings`` is the text of the hand-written settings file."""
    parsed = _parse_settings(settings)
    enabled = [use_case for use_case in declared.use_cases.values() if use_case.is_enabled]
    on_discord = persons.on_discord
    # With a person on Discord, every chat message is routed to a person's profile.
    served = [use_case for use_case in enabled if not (use_case.is_chat and on_discord)]
    in_use = _servers_named(declared, served)

    generated = {
        "platform_toolsets": _platform_toolsets(declared, served),
        "hooks": _hooks(declared),
        "mcp_servers": _mcp_servers(declared.gateway, in_use),
    }
    hermes_config = _config(
        "The hand-written settings.yaml first, then the parts rendered from persons.yaml\n"
        "# and use-cases.yaml.",
        _join_blocks(settings, parsed, _discord_blocks(on_discord)),
        "the default profile's source",
        _profile(persons.default_source, _HOME),
        "Rendered from use-cases.yaml: what each surface may hold, the tool servers,\n"
        "# and the hook that reports every finished turn.",
        generated,
    )
    holdings = {person.name: _held(declared, person) for person in persons.enabled_persons}
    profiles = {
        person.name: _person_config(declared, persons, person, holdings[person.name], settings)
        for person in persons.enabled_persons
    }
    profiles_kustomization = (
        f"{GENERATED_LINE}\n"
        f"# Each person's profile config as one key of {_PROFILES_CONFIG_MAP}, by handle; the\n"
        "# content hash rolls Hermes when one changes.\n"
        f"{_dump(_profiles_kustomization(profiles))}"
    )
    profiles_values = (
        f"{GENERATED_LINE}\n"
        "# An additional values file of Hermes's chart: each person's config and .env, the\n"
        "# persons' SOUL.md, AGENTS.md and the marker that keeps the bundled skills out,\n"
        "# each mounted read-only into the person's profile, and the container that\n"
        "# streams the profile's agent.log for Loki.\n"
        f"{_dump(_profiles_values(profiles))}"
    )
    jobs = [
        *(_cron_job(use_case) for use_case in enabled if use_case.is_schedule),
        *(_script_job(script) for script in declared.scripts.values() if script.is_enabled),
    ]
    cron_jobs = (
        f"{GENERATED_LINE}\n"
        "# The cron jobs the harness runs, one per enabled schedule use case and one per enabled "
        "script.\n"
        f"{_dump(dump_cron_jobs(jobs))}"
    )
    tracing = (
        f"{GENERATED_LINE}\n"
        "# The share of new traces every service of the agent platform keeps.\n"
        f"{SAMPLING_RATIO_VARIABLE}={declared.tracing.sampling_ratio!r}\n"
    )
    env_template = _template(
        HARNESS_KEYS,
        "# Each profile's .env, composed from the keys sealed one by one in\n"
        "# sealed-secret.yaml; Hermes mounts the default's read-only at the home's root,\n"
        "# a person's in their profile's directory.\n",
        {
            "default.env": _default_env(declared, enabled, in_use, persons, on_discord),
            **{
                f"{person.name}.env": _person_env(declared, persons, person, holdings[person.name])
                for person in persons.enabled_persons
            },
        },
    )
    routes = _routes(declared, in_use, persons, holdings)
    connectors = _connector_routes(declared, persons)
    routes_file = (
        f"{GENERATED_LINE}\n"
        "# The gateway's routes. A key is a variable the gateway expands at start, set from\n"
        f"# {GATEWAY_KEYS.name}, as is a connector's issuer; a credential is a file it reads\n"
        "# and watches.\n"
        f"{_dump(_gateway_config(declared, routes, connectors))}"
    )
    routes_values = (
        f"{GENERATED_LINE}\n"
        "# An additional values file of the gateway's chart: the routes' keys as variables, and\n"
        "# the routes and every credential they attach, mounted whole so a renewed one\n"
        "# reaches the gateway; a resealed key rolls it.\n"
        f"{_dump(_routes_values(routes, connectors))}"
    )
    return Rendering(
        hermes_config=hermes_config,
        profiles=profiles,
        profiles_kustomization=profiles_kustomization,
        profiles_values=profiles_values,
        cron_jobs=cron_jobs,
        tracing=tracing,
        env_template=env_template,
        routes=routes_file,
        routes_values=routes_values,
    )


