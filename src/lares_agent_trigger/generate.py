@dataclass(frozen=True)
class Rendering:
    """The rendered files, as text."""

    hermes_config: str
    # Each enabled person's profile config, by handle, in file order.
    profiles: dict[str, str]
    # The ConfigMap of those configs, and the chart values that mount every
    # person's files into their profile.
    profiles_kustomization: str
    profiles_values: str
    cron_jobs: str
    client_tools: str
    tracing: str
    env_template: str
    clients_template: str


class _Dumper(yaml.SafeDumper):
    """Block style with indented sequences, the way the repository writes YAML."""

    @override
    def increase_indent(self, flow: bool = False, indentless: bool = False) -> None:
        super().increase_indent(flow, False)

    @override
    def ignore_aliases(self, data: Any) -> bool:
        # A list rendered twice is written twice, never as an anchor and its alias.
        return True


def _text(dumper: yaml.SafeDumper, value: str) -> yaml.ScalarNode:
    # A file inside a file stays readable: a multi-line string is a literal block.
    style = "|" if "\n" in value else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", value, style=style)


_Dumper.add_representer(str, _text)


def _dump(data: Any) -> str:
    return yaml.dump(data, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=100)


def render(declared: UseCaseFile, persons: PersonsFile, settings: str) -> Rendering:
    """Render the declarations; ``settings`` is the text of the hand-written settings file."""
    parsed = _parse_settings(settings)
    enabled = [use_case for use_case in declared.use_cases.values() if use_case.is_enabled]
    on_discord = [person for person in persons.enabled_persons if person.discord is not None]
    # With a person on Discord, every chat message is routed to a person's profile.
    served = [use_case for use_case in enabled if not (use_case.is_chat and on_discord)]
    in_use = _servers_named(declared, served)
    bridges = [server for server in in_use if isinstance(server, BridgeServer)]

    generated = {
        "platform_toolsets": _platform_toolsets(declared, served),
        "hooks": _hooks(declared),
        "mcp_servers": _mcp_servers(in_use),
    }
    hermes_config = _config(
        "The hand-written settings.yaml first, then the parts rendered from persons.yaml\n"
        "# and use-cases.yaml.",
        _join_blocks(settings, parsed, _discord_blocks(on_discord)),
        "the default profile's source",
        _profile(persons.default_source, _HOME),
        "Rendered from use-cases.yaml: what each surface may hold, the tool servers,\n"
        "# and the hook that reports every finished turn.",
        generated,
    )
    holdings = {person.name: _held(declared, person) for person in persons.enabled_persons}
    profiles = {
        person.name: _person_config(declared, persons, person, holdings[person.name], settings)
        for person in persons.enabled_persons
    }
    profiles_kustomization = (
        f"{GENERATED_LINE}\n"
        f"# Each person's profile config as one key of {_PROFILES_CONFIG_MAP}, by handle; the\n"
        "# content hash rolls Hermes when one changes.\n"
        f"{_dump(_profiles_kustomization(profiles))}"
    )
    profiles_values = (
        f"{GENERATED_LINE}\n"
        "# An additional values file of Hermes's chart: each person's config and .env, the\n"
        "# persons' SOUL.md, AGENTS.md and the marker that keeps the bundled skills out,\n"
        "# each mounted read-only into the person's profile.\n"
        f"{_dump(_profiles_values(profiles))}"
    )
    jobs = [_cron_job(use_case) for use_case in enabled if use_case.is_schedule]
    cron_jobs = (
        f"{GENERATED_LINE}\n"
        "# The cron jobs the harness runs, one per enabled schedule use case.\n"
        f"{_dump(dump_cron_jobs(jobs))}"
    )
    # A person reads through a client of their own, named by the handle, and
    # places a request through the request server's machine client.
    reading = {
        handle: [tool for server in servers if _reads(server) for tool in server.tools]
        for handle, servers in holdings.items()
    }
    own = {handle: tools for handle, tools in reading.items() if tools}
    machines = {server.name for server in bridges} | {
        server.name
        for servers in holdings.values()
        for server in servers
        if isinstance(server, BridgeServer) and not _reads(server)
    }
    allowlists = {
        **{
            server.client: list(server.tools)
            for name, server in declared.tool_servers.items()
            if name in machines and isinstance(server, BridgeServer)
        },
        **own,
    }
    client_tools = (
        f"{GENERATED_LINE}\n"
        "# The tools each client of the bridge may see and call, and the clients that are\n"
        "# persons, named by their handles.\n"
        f"{CLIENT_TOOLS_VARIABLE}={json.dumps(allowlists, ensure_ascii=False)}\n"
        f"{PERSONS_VARIABLE}={json.dumps(list(own), ensure_ascii=False)}\n"
    )
    tracing = (
        f"{GENERATED_LINE}\n"
        "# The share of new traces every service of the agent platform keeps.\n"
        f"{SAMPLING_RATIO_VARIABLE}={declared.tracing.sampling_ratio!r}\n"
    )
    env_template = _template(
        HARNESS_KEYS,
        "# Each profile's .env, composed from the keys sealed one by one in\n"
        "# sealed-secret.yaml; Hermes mounts the default's read-only at the home's root,\n"
        "# a person's in their profile's directory.\n",
        {
            "default.env": _default_env(declared, enabled, bridges, persons, on_discord),
            **{
                f"{person.name}.env": _person_env(declared, persons, person, holdings[person.name])
                for person in persons.enabled_persons
            },
        },
    )
    clients_template = _template(
        BRIDGE_KEYS,
        "# The bridge's clients and their keys, composed from the keys sealed one by one\n"
        "# in sealed-secret.yaml, each under its client's name.\n",
        {"clients.json": _clients_json(allowlists)},
    )
    return Rendering(
        hermes_config=hermes_config,
        profiles=profiles,
        profiles_kustomization=profiles_kustomization,
        profiles_values=profiles_values,
        cron_jobs=cron_jobs,
        client_tools=client_tools,
        tracing=tracing,
        env_template=env_template,
        clients_template=clients_template,
    )


def _config(
    header: str,
    settings: str,
    source: str,
    profile: dict[str, Any],
    comment: str,
    generated: dict[str, Any],
) -> str:
    """One profile's config: the settings copied whole, comments and all, then the rendered part."""
    return (
        f"{GENERATED_LINE}\n"
        f"# {header}\n"
        "\n"
        f"{settings.rstrip()}\n"
        "\n"
        f"# Rendered from persons.yaml: {source}, its fallbacks in order,\n"
        "# and the profile's directory, where Hermes discovers the context files.\n"
        f"{_dump(profile)}"
        "\n"
        f"# {comment}\n"
        f"{_dump(generated)}"
    )


def _discord_user(person: Person) -> str:
    """The variable holding the person's Discord id, sealed in the default profile's .env."""
    return f"DISCORD_USER_{person.name.upper().replace('-', '_')}"


def _discord_blocks(on_discord: Sequence[Person]) -> dict[str, tuple[str, dict[str, Any]]]:
    """The default profile's Discord rights and routes, by the block they belong to.

    Every id is a reference to the default profile's .env: a missing one
    leaves its person ignored, never routed to the default profile. Without a
    person on Discord there is nothing to render.
    """
    if not on_discord:
        return {}
    ids = {person.name: f"${{env:{_discord_user(person)}}}" for person in on_discord}
    admins = [ids[person.name] for person in on_discord if person.discord == "admin"]
    routes = [
        {"name": handle, "platform": "discord", "user_id": user_id, "profile": handle}
        for handle, user_id in ids.items()
    ]
    return {
        "discord": (
            _DISCORD_COMMENT,
            {
                "allow_from": list(ids.values()),
                "allow_admin_from": admins,
                "group_allow_admin_from": admins,
                "user_allowed_commands": list(_PERSON_COMMANDS),
                "group_user_allowed_commands": list(_PERSON_COMMANDS),
            },
        ),
        "gateway": (_GATEWAY_COMMENT, {"profile_routes": routes}),
    }


def _join_blocks(
    settings: str, parsed: dict[str, Any], blocks: dict[str, tuple[str, dict[str, Any]]]
) -> str:
    """The settings with each rendered block's keys after the keys of the settings' own block.

    A block the settings do not hold follows them on its own. The settings
    stay text, comments and all; the result is read back to make sure it
    holds exactly the settings and the rendered keys.
    """
    lines = settings.rstrip().splitlines()
    alone: list[str] = []
    for name, (comment, keys) in blocks.items():
        if name not in parsed:
            alone.append(f"\n# {comment}\n{_dump({name: keys})}")
            continue
        start = next(
            (i for i, line in enumerate(lines) if re.fullmatch(rf"{name}:\s*(#.*)?", line)), None
        )
        if start is None:
            raise ValueError(
                f"`{name}` is written as a block mapping, one key per line, so the keys "
                "rendered from persons.yaml can join it"
            )
        end, indent = _block_end(lines, start)
        lines[end:end] = [
            f"{indent}{line}" if line else line
            for line in f"# {comment}\n{_dump(keys)}".rstrip().splitlines()
        ]
    joined = "\n".join(lines) + "\n" + "".join(alone)

    expected = dict(parsed)
    for name, (_, keys) in blocks.items():
        expected[name] = {**parsed.get(name, {}), **keys}
    if yaml.safe_load(joined) != expected:
        raise ValueError(
            "the rendered keys could not join the settings' blocks; check their indent"
        )
    return joined


def _block_end(lines: Sequence[str], start: int) -> tuple[int, str]:
    """Where a top-level block's last indented line ends, and the indent of its keys."""
    end, indent = start + 1, None
    for index in range(start + 1, len(lines)):
        line = lines[index]
        if not line.strip() or line.startswith("#"):
            continue
        if not line[0].isspace():
            break
        end = index + 1
        if indent is None and not line.lstrip().startswith("#"):
            indent = line[: len(line) - len(line.lstrip())]
    # Parsing the settings refuses a shared block that is empty or not a mapping.
    assert indent is not None
    return end, indent


def _person_config(
    declared: UseCaseFile,
    persons: PersonsFile,
    person: Person,
    held: Sequence[ToolServer],
    settings: str,
) -> str:
    """A person's profile: their source, their directory, and their tool servers.

    Discord keeps the harness's own Discord tools; the API server, where the
    web chat comes in, holds the same servers.
    """
    generated = {
        "platform_toolsets": {
            "discord": _surface("hermes-discord", held),
            "api_server": _surface(None, held),
        },
        "hooks": _hooks(declared),
        "mcp_servers": _mcp_servers(held),
    }
    return _config(
        f"{person.name}'s profile: the hand-written settings.yaml first, then the parts\n"
        "# rendered from persons.yaml and use-cases.yaml.",
        settings,
        f"{person.name}'s source",
        _profile(persons.source_of(person), _profile_directory(person.name)),
        f"Rendered from persons.yaml and use-cases.yaml: {person.name}'s tool servers on\n"
        "# Discord and the API server, and the hook that reports every finished turn.",
        generated,
    )


def _held(declared: UseCaseFile, person: Person) -> list[ToolServer]:
    """The tool servers a person holds, in file order."""
    return [server for name, server in declared.tool_servers.items() if name in person.tools]


def _reads(server: ToolServer) -> TypeIs[BridgeServer]:
    """True for a bridge server a person reads through a client of their own.

    Any other bridge server a person holds, one that places requests, they
    reach through its machine client, under its key.
    """
    return isinstance(server, BridgeServer) and server.access == "read"


def _profile_directory(handle: str) -> str:
    """Where Hermes keeps a named profile: under the home's `profiles/`."""
    return f"{_HOME}/profiles/{handle}"


def _profiles_kustomization(handles: Iterable[str]) -> dict[str, Any]:
    """The ConfigMap of the persons' configs, generated even when empty.

    kustomize refuses a kustomization that holds nothing.
    """
    return {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "configMapGenerator": [
            {
                "name": _PROFILES_CONFIG_MAP,
                "files": [f"{handle}={handle}/{_CONFIG_FILE}" for handle in handles],
            }
        ],
    }


def _profiles_values(handles: Iterable[str]) -> dict[str, Any]:
    """The volumes and mounts of every person's files, each a read-only subPath mount.

    The chart keys a mount by its volume, so each profile mounts volumes of its own.
    """
    volumes: dict[str, Any] = {}
    mounts: dict[str, Any] = {}
    for handle in handles:
        files = [
            (
                "env",
                {"secret": {"secretName": HARNESS_KEYS.name, **_item(f"{handle}.env", ".env")}},
                ".env",
            ),
            (
                "config",
                {"configMap": {"name": _PROFILES_CONFIG_MAP, **_item(handle, _CONFIG_FILE)}},
                _CONFIG_FILE,
            ),
            *(
                (part, {"configMap": {"name": _SHARED_CONFIG_MAP, **_item(key, file)}}, file)
                for part, key, file in _SHARED_FILES
            ),
        ]
        for part, volume, file in files:
            name = f"hermes-{handle}-{part}"
            volumes[name] = volume
            mounts[name] = {
                "mountPath": f"{_profile_directory(handle)}/{file}",
                "subPath": file,
                "readOnly": True,
            }
    return {"deployment": {"volumes": volumes, "volumeMounts": mounts}}


def _item(key: str, path: str) -> dict[str, list[dict[str, str]]]:
    """A volume's one file: the key it is read from and the file it becomes."""
    return {"items": [{"key": key, "path": path}]}


def _parse_settings(settings: str) -> dict[str, Any]:
    try:
        parsed = yaml.safe_load(settings)
    except yaml.YAMLError as exc:
        raise ValueError(f"is not valid YAML ({exc})") from exc
    if not isinstance(parsed, dict):
        raise ValueError("must be a mapping of harness settings")
    for source, keys in RENDERED_KEYS.items():
        for key in keys:
            if key in parsed:
                raise ValueError(f"`{key}` is rendered from {source}; remove it here")
    for block, keys in SHARED_BLOCKS.items():
        if block not in parsed:
            continue
        own = parsed[block]
        if not isinstance(own, dict) or not own:
            raise ValueError(f"`{block}` must be a mapping of settings, or left out")
        for key in keys:
            if key in own:
                raise ValueError(f"`{block}.{key}` is rendered from persons.yaml; remove it here")
    return parsed


def _profile(source: ModelSource, directory: str) -> dict[str, Any]:
    """The harness's `model` and `fallback_providers` from the source, and the working directory."""
    return {
        "model": {"provider": source.provider, "default": source.model},
        "fallback_providers": [
            {"provider": step.provider, "model": step.model} for step in source.fallback
        ],
        "terminal": {"cwd": directory},
    }


def _servers_named(
    declared: UseCaseFile, use_cases: Iterable[UseCase], access: ToolAccess | None = None
) -> list[ToolServer]:
    """The servers these use cases name, once each and in file order, optionally of one access."""
    named = {name for use_case in use_cases for name in use_case.tools}
    return [
        server
        for name, server in declared.tool_servers.items()
        if name in named and (access is None or server.access == access)
    ]


def _cron_servers(declared: UseCaseFile, enabled: Sequence[UseCase]) -> list[ToolServer]:
    """Every read server in use and the memory servers schedule use cases name, in file order."""
    schedules = [use_case for use_case in enabled if use_case.is_schedule]
    held = {
        *(server.name for server in _servers_named(declared, enabled, access="read")),
        *(server.name for server in _servers_named(declared, schedules, access="memory")),
    }
    return [server for name, server in declared.tool_servers.items() if name in held]


def _surface(composite: str | None, servers: Sequence[ToolServer]) -> list[str]:
    head = [composite] if composite is not None else []
    return [*head, *([server.name for server in servers] or [_NO_TOOL_SERVER])]


def _platform_toolsets(declared: UseCaseFile, enabled: Sequence[UseCase]) -> dict[str, list[str]]:
    chat = [use_case for use_case in enabled if use_case.is_chat]
    events = [use_case for use_case in enabled if use_case.event_trigger is not None]
    return {
        "discord": _surface("hermes-discord", _servers_named(declared, chat)),
        "api_server": _surface(None, _servers_named(declared, events)),
        "cron": _surface("hermes-cron", _cron_servers(declared, enabled)),
    }


def _hooks(declared: UseCaseFile) -> dict[str, Any]:
    hook = declared.ledger_hook
    return {
        "outbound": [
            {
                "name": _HOOK_NAME,
                "url": f"{hook.trigger_url.rstrip('/')}{HOOK_PATH}",
                "events": [MODEL_CALL, TOOL_CALL, TURN_ENDED],
                "secret_env": hook.secret_env,
                "timeout": _HOOK_TIMEOUT_SECONDS,
            }
        ]
    }


def _mcp_servers(in_use: Sequence[ToolServer]) -> dict[str, Any]:
    return {
        server.name: _bridge_entry(server)
        if isinstance(server, BridgeServer)
        else _github_entry(server)
        for server in in_use
    }


def _bridge_entry(server: BridgeServer) -> dict[str, Any]:
    return {
        "url": server.url,
        "headers": {"Authorization": f"Bearer ${{env:{server.key_env}}}"},
        "timeout": server.timeout_seconds,
        "tools": {"include": list(server.tools)},
    }


def _github_entry(server: GitHubServer) -> dict[str, Any]:
    return {
        "command": server.command,
        "args": ["stdio", "--read-only", f"--toolsets={','.join(server.toolsets)}"],
        # The server mints and renews the App's installation tokens itself.
        "env": {
            "GITHUB_APP_ID": str(server.app_id),
            "GITHUB_APP_INSTALLATION_ID": str(server.installation_id),
            "GITHUB_APP_PRIVATE_KEY_PATH": server.private_key_file,
        },
        "timeout": server.timeout_seconds,
        "tools": {
            "include": list(server.tools),
            # Its prompts walk the model towards writes it does not hold; its
            # resources repeat what the read tools return.
            "resources": False,
            "prompts": False,
        },
    }


def _sealed_key(variable: str) -> str:
    """The key a variable's value is sealed under: its name, lower case and dashed."""
    return variable.lower().replace("_", "-")


def _default_env(
    declared: UseCaseFile,
    enabled: Sequence[UseCase],
    bridges: Sequence[BridgeServer],
    persons: PersonsFile,
    on_discord: Sequence[Person],
) -> str:
    """Every key the default profile's config reads, once each, as a line naming its sealed key.

    The bot serves the chat for every profile, so its token stays here as
    long as the chat is on, beside the Discord id of each person it routes.
    """
    variables = [
        _API_SERVER_KEY,
        *([_DISCORD_BOT_TOKEN] if any(use_case.is_chat for use_case in enabled) else []),
        *(_discord_user(person) for person in on_discord),
        declared.ledger_hook.secret_env,
        *(server.key_env for server in bridges),
        *persons.default_source.key_envs,
    ]
    return _env_lines(dict.fromkeys(variables), _sealed_key)


def _person_env(
    declared: UseCaseFile, persons: PersonsFile, person: Person, held: Sequence[ToolServer]
) -> str:
    """Every key a person's config reads: their own, sealed under the handle, and the shared ones.

    Their own are the API server's key, the key of their bridge client and
    the keys of their source's providers; the hook secret and a machine
    client's key are the ones every holder shares.
    """
    source = persons.source_of(person)
    own = {
        _API_SERVER_KEY,
        *(server.key_env for server in held if _reads(server)),
        *source.key_envs,
    }
    variables = [
        _API_SERVER_KEY,
        declared.ledger_hook.secret_env,
        *(server.key_env for server in held if isinstance(server, BridgeServer)),
        *source.key_envs,
    ]

    def sealed(variable: str) -> str:
        key = _sealed_key(variable)
        return f"{person.name}-{key}" if variable in own else key

    return _env_lines(dict.fromkeys(variables), sealed)


def _env_lines(variables: Iterable[str], sealed: Callable[[str], str]) -> str:
    """One `.env` line per variable, naming the key its value is sealed under."""
    return "".join(
        f"""{variable}='{{{{ index . "{sealed(variable)}" }}}}'\n""" for variable in variables
    )


def _clients_json(clients: Iterable[str]) -> str:
    """The bridge's clients file: each client's name and the key sealed under that name."""
    entries = ",\n".join(
        f"""  "{client}": {{{{ index . "{client}" | toJson }}}}""" for client in clients
    )
    return f"{{\n{entries}\n}}\n"


def _template(target: SealedSecret, comment: str, files: dict[str, str]) -> str:
    """A patch adding the files to their SealedSecret as templates of the sealed keys.

    kubeseal rewrites the SealedSecret whole, so the templates sit beside it.
    """
    patch = {
        "apiVersion": "bitnami.com/v1alpha1",
        "kind": "SealedSecret",
        "metadata": {"name": target.name, "namespace": target.namespace},
        "spec": {"template": {"data": files}},
    }
    return f"{GENERATED_LINE}\n{comment}{_dump(patch)}"


def _cron_job(use_case: UseCase) -> CronJob:
    trigger = use_case.trigger
    assert isinstance(trigger, ScheduleTrigger)
    # The loader refuses a schedule use case that names no skill.
    assert use_case.skill is not None
    budget = use_case.budget
    return CronJob(
        name=job_name(use_case),
        schedule=trigger.cron,
        skills=(use_case.skill,),
        prompt=(
            f"Answer in {language_name(use_case.language)}. "
            f"Stay within {budget.tool_calls} tool calls and {budget.minutes} minutes."
        ),
        # The trigger delivers; the harness keeps the output to itself.
        deliver="local",
    )


def main(argv: Sequence[str] | None = None) -> int:
    """`lares-agent-trigger generate`: render the declarations and write every file."""
    parser = argparse.ArgumentParser(
        prog="lares-agent-trigger generate",
        description="Render the use-case file and the person declaration into the harness "
        "configuration, each person's profile, the cron job set, the bridge's allowlists, the "
        "sampling ratio, and the templates of every profile's .env and the bridge's clients "
        "file.",
    )
    parser.add_argument("--use-cases", type=Path, required=True)
    parser.add_argument("--persons", type=Path, required=True)
    parser.add_argument("--settings", type=Path, required=True)
    parser.add_argument("--hermes-config", type=Path, required=True)
    parser.add_argument("--cron-jobs", type=Path, required=True)
    parser.add_argument("--client-tools", type=Path, required=True)
    parser.add_argument("--tracing", type=Path, required=True)
    parser.add_argument("--env-template", type=Path, required=True)
    parser.add_argument("--clients-template", type=Path, required=True)
    # Written whole: each person's config, the ConfigMap of them and the chart values.
    parser.add_argument("--profiles", type=Path, required=True)
    args = parser.parse_args(argv)

    try:
        declared = load_use_case_file(args.use_cases)
        persons = load_persons_file(args.persons, declared)
        try:
            settings = args.settings.read_text(encoding="utf-8")
        except OSError as exc:
            raise ValueError(f"{args.settings}: cannot be read ({exc})") from exc
        try:
            rendered = render(declared, persons, settings)
        except ValueError as exc:
            raise ValueError(f"{args.settings}: {exc}") from exc
    except ValueError as exc:
        print(f"generate: {exc}", file=sys.stderr)
        return 1

    profiles: Path = args.profiles
    files = [
        (args.hermes_config, rendered.hermes_config),
        (args.cron_jobs, rendered.cron_jobs),
        (args.client_tools, rendered.client_tools),
        (args.tracing, rendered.tracing),
        (args.env_template, rendered.env_template),
        (args.clients_template, rendered.clients_template),
        (profiles / "kustomization.yaml", rendered.profiles_kustomization),
        (profiles / "profiles.values.yaml", rendered.profiles_values),
        *((profiles / handle / _CONFIG_FILE, text) for handle, text in rendered.profiles.items()),
    ]
    try:
        for path, text in files:
            # The profiles' directory is the generator's own, down to each handle's.
            if path.is_relative_to(profiles):
                path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
        _remove_stale_profiles(profiles, rendered.profiles)
    except OSError as exc:
        print(f"generate: {exc.filename}: cannot be written ({exc.strerror})", file=sys.stderr)
        return 1
    return 0


def _remove_stale_profiles(profiles: Path, rendered: Iterable[str]) -> None:
    """Remove the config of every person not rendered, and its emptied directory."""
    kept = set(rendered)
    for stale in profiles.glob(f"*/{_CONFIG_FILE}"):
        if stale.parent.name in kept:
            continue
        stale.unlink()
        if not any(stale.parent.iterdir()):
            stale.parent.rmdir()
