def _discord_user(person: Person) -> str:
    """The variable holding the person's Discord id, sealed in the default profile's .env."""
    return f"DISCORD_USER_{person.name.upper().replace('-', '_')}"


def _discord_blocks(on_discord: Sequence[Person]) -> dict[str, tuple[str, dict[str, Any]]]:
    """The default profile's Discord rights and routes, by the block they belong to.

    Every id is a reference to the default profile's .env: a missing one
    leaves its person ignored, never routed to the default profile. Without a
    person on Discord there is nothing to render.
    """
    if not on_discord:
        return {}
    ids = {person.name: f"${{env:{_discord_user(person)}}}" for person in on_discord}
    admins = [ids[person.name] for person in on_discord if person.discord == "admin"]
    routes = [
        {"name": handle, "platform": "discord", "user_id": user_id, "profile": handle}
        for handle, user_id in ids.items()
    ]
    return {
        "discord": (
            _DISCORD_COMMENT,
            {
                "allow_from": list(ids.values()),
                "allow_admin_from": admins,
                "group_allow_admin_from": admins,
                "user_allowed_commands": list(_PERSON_COMMANDS),
                "group_user_allowed_commands": list(_PERSON_COMMANDS),
            },
        ),
        "gateway": (_GATEWAY_COMMENT, {"profile_routes": routes}),
    }


def _join_blocks(
    settings: str, parsed: dict[str, Any], blocks: dict[str, tuple[str, dict[str, Any]]]
) -> str:
    """The settings with each rendered block's keys after the keys of the settings' own block.

    A block the settings do not hold follows them on its own. The settings
    stay text, comments and all; the result is read back to make sure it
    holds exactly the settings and the rendered keys.
    """
    lines = settings.rstrip().splitlines()
    alone: list[str] = []
    for name, (comment, keys) in blocks.items():
        if name not in parsed:
            alone.append(f"\n# {comment}\n{_dump({name: keys})}")
            continue
        start = next(
            (i for i, line in enumerate(lines) if re.fullmatch(rf"{name}:\s*(#.*)?", line)), None
        )
        if start is None:
            raise ValueError(
                f"`{name}` is written as a block mapping, one key per line, so the keys "
                "rendered from persons.yaml can join it"
            )
        end, indent = _block_end(lines, start)
        lines[end:end] = [
            f"{indent}{line}" if line else line
            for line in f"# {comment}\n{_dump(keys)}".rstrip().splitlines()
        ]
    joined = "\n".join(lines) + "\n" + "".join(alone)

    expected = dict(parsed)
    for name, (_, keys) in blocks.items():
        expected[name] = {**parsed.get(name, {}), **keys}
    if yaml.safe_load(joined) != expected:
        raise ValueError(
            "the rendered keys could not join the settings' blocks; check their indent"
        )
    return joined


def _block_end(lines: Sequence[str], start: int) -> tuple[int, str]:
    """Where a top-level block's last indented line ends, and the indent of its keys."""
    end, indent = start + 1, None
    for index in range(start + 1, len(lines)):
        line = lines[index]
        if not line.strip() or line.startswith("#"):
            continue
        if not line[0].isspace():
            break
        end = index + 1
        if indent is None and not line.lstrip().startswith("#"):
            indent = line[: len(line) - len(line.lstrip())]
    # Parsing the settings refuses a shared block that is empty or not a mapping.
    assert indent is not None
    return end, indent


def _person_config(
    declared: UseCaseFile,
    persons: PersonsFile,
    person: Person,
    held: Sequence[ToolServer],
    settings: str,
) -> str:
    """A person's profile: their source, their directory, and their tool servers.

    Discord keeps the harness's own Discord tools; the API server, where the
    web chat comes in, holds the same servers and the harness's skill tools.
    """
    generated = {
        "platform_toolsets": {
            "discord": _surface("hermes-discord", held),
            "api_server": _surface(_SKILLS_TOOLSET, held),
        },
        "hooks": _hooks(declared),
        "mcp_servers": _mcp_servers(declared.gateway, held),
    }
    return _config(
        f"{person.name}'s profile: the hand-written settings.yaml first, then the parts\n"
        "# rendered from persons.yaml and use-cases.yaml.",
        settings,
        f"{person.name}'s source",
        _profile(persons.source_of(person), _profile_directory(person.name)),
        f"Rendered from persons.yaml and use-cases.yaml: {person.name}'s tool servers on\n"
        "# Discord and the API server, the web chat's skill tools, and the hook that\n"
        "# reports every finished turn.",
        generated,
    )


def _held(declared: UseCaseFile, person: Person) -> list[ToolServer]:
    """The tool servers a person holds, in file order."""
    return [server for name, server in declared.tool_servers.items() if name in person.tools]


def _profile_directory(handle: str) -> str:
    """Where Hermes keeps a named profile: under the home's `profiles/`."""
    return f"{_HOME}/profiles/{handle}"


def _profiles_kustomization(handles: Iterable[str]) -> dict[str, Any]:
    """The ConfigMap of the persons' configs, generated even when empty.

    kustomize refuses a kustomization that holds nothing.
    """
    return {
        "apiVersion": "kustomize.config.k8s.io/v1beta1",
        "kind": "Kustomization",
        "configMapGenerator": [
            {
                "name": _PROFILES_CONFIG_MAP,
                "files": [f"{handle}={handle}/{_CONFIG_FILE}" for handle in handles],
            }
        ],
    }


def _profiles_values(handles: Iterable[str]) -> dict[str, Any]:
    """The volumes and mounts of every person's files, each a read-only subPath mount, and
    the container that streams each person's log.

    The chart keys a mount by its volume, so each profile mounts volumes of its own.
    """
    volumes: dict[str, Any] = {}
    mounts: dict[str, Any] = {}
    containers: dict[str, Any] = {}
    for handle in handles:
        containers[f"{_LOG_CONTAINER}-{handle}"] = _log_container(handle)
        files = [
            (
                "env",
                {"secret": {"secretName": HARNESS_KEYS.name, **_item(f"{handle}.env", ".env")}},
                ".env",
            ),
            (
                "config",
                {"configMap": {"name": _PROFILES_CONFIG_MAP, **_item(handle, _CONFIG_FILE)}},
                _CONFIG_FILE,
            ),
            *(
                (part, {"configMap": {"name": _SHARED_CONFIG_MAP, **_item(key, file)}}, file)
                for part, key, file in _SHARED_FILES
            ),
        ]
        for part, volume, file in files:
            name = f"hermes-{handle}-{part}"
            volumes[name] = volume
            mounts[name] = {
                "mountPath": f"{_profile_directory(handle)}/{file}",
                "subPath": file,
                "readOnly": True,
            }
    return {
        "deployment": {
            "volumes": volumes,
            "volumeMounts": mounts,
            "additionalContainers": containers,
        }
    }


def _log_container(handle: str) -> dict[str, Any]:
    """Streams the profile's agent.log from its end, reading the volume as the harness's user."""
    return {
        "image": _LOG_IMAGE,
        "command": ["tail", "-n", "0", "-F", f"{_profile_directory(handle)}/logs/agent.log"],
        "volumeMounts": [{"name": _DATA_VOLUME, "mountPath": _HOME, "readOnly": True}],
        "securityContext": {
            "runAsUser": _HERMES_UID,
            "runAsGroup": _HERMES_UID,
            "runAsNonRoot": True,
            "readOnlyRootFilesystem": True,
            "allowPrivilegeEscalation": False,
            "capabilities": {"drop": ["ALL"]},
        },
    }


def _item(key: str, path: str) -> dict[str, list[dict[str, str]]]:
    """A volume's one file: the key it is read from and the file it becomes."""
    return {"items": [{"key": key, "path": path}]}


def _parse_settings(settings: str) -> dict[str, Any]:
    try:
        parsed = yaml.safe_load(settings)
    except yaml.YAMLError as exc:
        raise ValueError(f"is not valid YAML ({exc})") from exc
    if not isinstance(parsed, dict):
        raise ValueError("must be a mapping of harness settings")
    for source, keys in RENDERED_KEYS.items():
        for key in keys:
            if key in parsed:
                raise ValueError(f"`{key}` is rendered from {source}; remove it here")
    for block, keys in SHARED_BLOCKS.items():
        if block not in parsed:
            continue
        own = parsed[block]
        if not isinstance(own, dict) or not own:
            raise ValueError(f"`{block}` must be a mapping of settings, or left out")
        for key in keys:
            if key in own:
                raise ValueError(f"`{block}.{key}` is rendered from persons.yaml; remove it here")
    return parsed


def _profile(source: ModelSource, directory: str) -> dict[str, Any]:
    """The harness's `model` and `fallback_providers` from the source, and the working directory."""
    return {
        "model": {"provider": source.provider, "default": source.model},
        "fallback_providers": [
            {"provider": step.provider, "model": step.model} for step in source.fallback
        ],
        "terminal": {"cwd": directory},
    }


def _servers_named(
    declared: UseCaseFile, use_cases: Iterable[UseCase], access: ToolAccess | None = None
) -> list[ToolServer]:
    """The servers these use cases name, once each and in file order, optionally of one access."""
    named = {name for use_case in use_cases for name in use_case.tools}
    return [
        server
        for name, server in declared.tool_servers.items()
        if name in named and (access is None or server.access == access)
    ]


def _cron_servers(declared: UseCaseFile, enabled: Sequence[UseCase]) -> list[ToolServer]:
    """Every read server in use and the memory servers schedule use cases name, in file order."""
    schedules = [use_case for use_case in enabled if use_case.is_schedule]
    held = {
        *(server.name for server in _servers_named(declared, enabled, access="read")),
        *(server.name for server in _servers_named(declared, schedules, access="memory")),
    }
    return [server for name, server in declared.tool_servers.items() if name in held]


def _surface(own: str | None, servers: Sequence[ToolServer]) -> list[str]:
    """A platform's list: the harness's own tools, if any, then the servers or `no_mcp`."""
    head = [own] if own is not None else []
    return [*head, *([server.name for server in servers] or [_NO_TOOL_SERVER])]


def _platform_toolsets(declared: UseCaseFile, enabled: Sequence[UseCase]) -> dict[str, list[str]]:
    chat = [use_case for use_case in enabled if use_case.is_chat]
    events = [use_case for use_case in enabled if use_case.event_trigger is not None]
    return {
        "discord": _surface("hermes-discord", _servers_named(declared, chat)),
        "api_server": _surface(None, _servers_named(declared, events)),
        "cron": _surface("hermes-cron", _cron_servers(declared, enabled)),
    }


